-- Run this once in the Supabase SQL editor IN THE INVENTORY PROJECT. Safe to repeat.
-- Run it after add_budget_categories.sql and add_projects_layer.sql (and add_app_settings.sql, for is_app_admin()).
--
-- The Budget tab: how much is budgeted for each budget category at each site, per year, set against what has
-- been spent (issued POs and approved invoices -- the tab works those out from the POs; nothing about spending
-- is stored here).
--
--   * public.budget_amounts: one row per year + site + budget category (+ optional sub-category, e.g. a
--     Planned Initiative). A category/site with no row is simply "not budgeted" (the sheet's N/A).
--   * Who can read it: admin and the accounting roles (the same people as the Audit tab). Who can change it: admin.
--   * Seeds the 2026 Regular O&M budget from "O&M Budget Check Thru Sept 1.xlsx" (2026 Budget section), once --
--     only for sites/categories that have no 2026 amount yet, so re-running never overwrites an edit made in
--     the app. Roof Repair and Hawkeye (Firelight Solar LP only) are added as Regular O&M budget categories.
--     FLOPS (Firelight Operations LP) has no budget in that file, so it has no rows.

create table if not exists public.budget_amounts (
  id bigint generated by default as identity primary key,
  year integer not null check (year between 2000 and 2100),
  project_id bigint not null references public.projects(id) on delete cascade,
  category_id bigint not null references public.budget_categories(id) on delete cascade,
  subcategory_id bigint references public.budget_subcategories(id) on delete cascade,
  amount numeric(14, 2) not null default 0,
  updated_at timestamptz not null default now(),
  updated_by bigint references public.users(id) on delete set null
);

create unique index if not exists budget_amounts_unique
  on public.budget_amounts (year, project_id, category_id, coalesce(subcategory_id, 0));
create index if not exists budget_amounts_year_idx on public.budget_amounts (year);

create or replace function public.can_view_budget()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.users u
    where u.auth_user_id = auth.uid()
      and u.active
      and u.roles && array['admin', 'invoice_matching', 'invoice_approval', 'payment']::text[]
  );
$$;
revoke all on function public.can_view_budget() from public, anon;
grant execute on function public.can_view_budget() to authenticated, service_role;

-- Who changed it and when: stamped here, whatever the browser sends.
create or replace function public.fn_budget_amount_stamp()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new.updated_at := now();
  new.updated_by := public.current_app_user_id();
  return new;
end;
$$;
revoke all on function public.fn_budget_amount_stamp() from public, anon, authenticated;

-- current_app_user_id() comes from add_suggestions.sql; make sure it exists so this file stands alone.
create or replace function public.current_app_user_id()
returns bigint
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select u.id from public.users u where u.auth_user_id = auth.uid() and u.active;
$$;
revoke all on function public.current_app_user_id() from public, anon;
grant execute on function public.current_app_user_id() to authenticated, service_role;

drop trigger if exists trg_budget_amount_stamp on public.budget_amounts;
create trigger trg_budget_amount_stamp
  before insert or update on public.budget_amounts
  for each row execute function public.fn_budget_amount_stamp();

alter table public.budget_amounts enable row level security;

drop policy if exists "budget read" on public.budget_amounts;
create policy "budget read" on public.budget_amounts for select to authenticated using (public.can_view_budget());
drop policy if exists "budget admin insert" on public.budget_amounts;
create policy "budget admin insert" on public.budget_amounts for insert to authenticated with check (public.is_app_admin());
drop policy if exists "budget admin update" on public.budget_amounts;
create policy "budget admin update" on public.budget_amounts for update to authenticated
  using (public.is_app_admin()) with check (public.is_app_admin());
drop policy if exists "budget admin delete" on public.budget_amounts;
create policy "budget admin delete" on public.budget_amounts for delete to authenticated using (public.is_app_admin());

grant select, insert, update, delete on public.budget_amounts to authenticated, service_role;

-- The two Firelight Solar categories that only exist in the budget file (Regular O&M).
insert into public.budget_categories (program_id, name)
select g.id, v.n
from public.programs g, (values ('Roof Repair'), ('Hawkeye')) as v(n)
where g.name = 'Regular O&M'
  and not exists (select 1 from public.budget_categories c where c.program_id = g.id and lower(c.name) = lower(v.n));

