-- Run this once in the Supabase SQL editor IN THE INVENTORY PROJECT. Safe to repeat.
-- Run it after add_invoice_approval_flow.sql (and add_invoice_duplicate_guard.sql). It replaces
-- add_po_links_and_invoice_split.sql: if you already ran that one, nothing needs undoing (its two extra invoice
-- columns, covers / invoice_total, are simply no longer used) and this file reuses the links table it made.
--
-- When a vendor invoices for MORE than the PO (usually shipping added afterwards), the PO can't just be paid
-- over its total. The person adding the invoice flags it ("over the PO"); when it reaches the requisitioner
-- their only way forward is to void the PO and regenerate it: a copy goes back to the Purchase Requisition
-- stage (a draft) with the invoice attached, and the prices are adjusted up to the invoice before it is submitted
-- again. The old and the new PO are linked, so each shows the other.
--
--   invoices.exceeds_po / exceeds_note : the flag, and an optional note (e.g. "shipping added")
--   a trigger: a flagged invoice can't be approved by the requisitioner (it has to go the regenerate route)
--   purchase_request_links             : POs linked to each other (by hand, or old <-> regenerated PO)

alter table public.invoices add column if not exists exceeds_po boolean not null default false;
alter table public.invoices add column if not exists exceeds_note text;

create or replace function public.fn_invoice_exceeds_guard()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.exceeds_po and new.reviewed and not coalesce(old.reviewed, false) then
    raise exception 'This invoice is for more than the PO, so the PO has to be voided and regenerated at the new amount instead of approving it.' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'invoices' and column_name = 'reviewed') then
    drop trigger if exists trg_invoice_exceeds_guard on public.invoices;
    create trigger trg_invoice_exceeds_guard
      before update on public.invoices
      for each row execute function public.fn_invoice_exceeds_guard();
  end if;
end $$;

-- POs linked to each other. `reason` is 'regenerated' when request_a was voided and request_b is its replacement.
create table if not exists public.purchase_request_links (
  id bigint generated by default as identity primary key,
  request_a bigint not null references public.purchase_requests(id) on delete cascade,
  request_b bigint not null references public.purchase_requests(id) on delete cascade,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now(),
  constraint purchase_request_links_distinct check (request_a <> request_b)
);
alter table public.purchase_request_links add column if not exists reason text;

create unique index if not exists purchase_request_links_pair
  on public.purchase_request_links (least(request_a, request_b), greatest(request_a, request_b));

-- Who made the link is the signed-in user, not whatever the browser says.
create or replace function public.fn_po_link_stamp()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare uid bigint;
begin
  select u.id into uid from public.users u where u.auth_user_id = auth.uid() and u.active;
  new.created_by := coalesce(uid, new.created_by);
  new.created_at := now();
  return new;
end;
$$;

drop trigger if exists trg_po_link_stamp on public.purchase_request_links;
create trigger trg_po_link_stamp
  before insert on public.purchase_request_links
  for each row execute function public.fn_po_link_stamp();

do $$
declare check_expr text;
begin
  check_expr := case when to_regprocedure('public.is_active_app_user()') is not null
                     then 'public.is_active_app_user()' else 'true' end;
  alter table public.purchase_request_links enable row level security;
  drop policy if exists "Allow public read" on public.purchase_request_links;
  drop policy if exists "Allow public insert" on public.purchase_request_links;
  drop policy if exists "Allow public delete" on public.purchase_request_links;
  execute format('create policy "Allow public read" on public.purchase_request_links for select using (%s)', check_expr);
  execute format('create policy "Allow public insert" on public.purchase_request_links for insert with check (%s)', check_expr);
  execute format('create policy "Allow public delete" on public.purchase_request_links for delete using (%s)', check_expr);
end $$;
