-- Run this once in the Supabase SQL editor IN THE INVENTORY PROJECT. Safe to repeat.
-- Run it after add_invoice_duplicate_guard.sql (and add_po_history.sql, so the new invoice fields show up
-- in the PO History under their own names; it works without it).
--
-- Two things for the case where a vendor invoices more than the PO (usually shipping added afterwards) and
-- a second PO is raised for the difference:
--
-- 1. One vendor invoice can be split across several POs. Each PO still has its own invoice row (and file)
--    for just its share of the amount; the row now also remembers the whole invoice's total
--    (`invoice_total`) and which items on the invoice that PO took (`covers`, e.g. "Shipping / handling").
--    The app works out the split when the invoice is added (it reads the line items off the PDF).
-- 2. POs can be linked to each other by hand (`purchase_request_links`). POs that share an invoice number
--    from the same vendor are shown as related automatically; this table is for links made by number.

alter table public.invoices add column if not exists invoice_total numeric;
alter table public.invoices add column if not exists covers text;

create table if not exists public.purchase_request_links (
  id bigint generated by default as identity primary key,
  request_a bigint not null references public.purchase_requests(id) on delete cascade,
  request_b bigint not null references public.purchase_requests(id) on delete cascade,
  created_by bigint references public.users(id),
  created_at timestamptz not null default now(),
  constraint purchase_request_links_distinct check (request_a <> request_b)
);

-- One link per pair, whichever way round it was entered.
create unique index if not exists purchase_request_links_pair
  on public.purchase_request_links (least(request_a, request_b), greatest(request_a, request_b));

-- Who made the link is the signed-in user, not whatever the browser says.
create or replace function public.fn_po_link_stamp()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare uid bigint;
begin
  select u.id into uid from public.users u where u.auth_user_id = auth.uid() and u.active;
  new.created_by := coalesce(uid, new.created_by);
  new.created_at := now();
  return new;
end;
$$;

drop trigger if exists trg_po_link_stamp on public.purchase_request_links;
create trigger trg_po_link_stamp
  before insert on public.purchase_request_links
  for each row execute function public.fn_po_link_stamp();

do $$
declare check_expr text;
begin
  check_expr := case when to_regprocedure('public.is_active_app_user()') is not null
                     then 'public.is_active_app_user()' else 'true' end;
  alter table public.purchase_request_links enable row level security;
  drop policy if exists "Allow public read" on public.purchase_request_links;
  drop policy if exists "Allow public insert" on public.purchase_request_links;
  drop policy if exists "Allow public delete" on public.purchase_request_links;
  execute format('create policy "Allow public read" on public.purchase_request_links for select using (%s)', check_expr);
  execute format('create policy "Allow public insert" on public.purchase_request_links for insert with check (%s)', check_expr);
  execute format('create policy "Allow public delete" on public.purchase_request_links for delete using (%s)', check_expr);
end $$;
