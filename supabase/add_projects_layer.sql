-- Everyone who can use the app can read these; changing them is checked in the app (Admin tab) like the
-- budget categories. Same signed-in check the other tables use once security_02 has been run.
do $$
declare t text; check_expr text;
begin
  check_expr := case when to_regprocedure('public.is_active_app_user()') is not null
                     then 'public.is_active_app_user()' else 'true' end;
  foreach t in array array['programs', 'program_sites'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "Allow public read" on public.%I', t);
    execute format('drop policy if exists "Allow public insert" on public.%I', t);
    execute format('drop policy if exists "Allow public update" on public.%I', t);
    execute format('drop policy if exists "Allow public delete" on public.%I', t);
    execute format('create policy "Allow public read" on public.%I for select using (%s)', t, check_expr);
    execute format('create policy "Allow public insert" on public.%I for insert with check (%s)', t, check_expr);
    execute format('create policy "Allow public update" on public.%I for update using (%s)', t, check_expr);
    execute format('create policy "Allow public delete" on public.%I for delete using (%s)', t, check_expr);
  end loop;
end $$;

-- 2. Sites ---------------------------------------------------------------------------------------

update public.projects set name = 'Firelight Operations LP'
where name = 'FLOPS' and not exists (select 1 from public.projects where name = 'Firelight Operations LP');

-- Regular O&M gets every site there is today (only the first time: later sites are added in the Admin tab).
insert into public.program_sites (program_id, project_id)
select om.id, p.id
from public.programs om, public.projects p
where om.name = 'Regular O&M'
  and not exists (select 1 from public.program_sites ps where ps.program_id = om.id)
on conflict do nothing;

-- The two sites that only exist for the repower projects. They hold no parts.
insert into public.projects (name)
select v.n from (values ('378 Elgin'), ('6 Manchester')) as v(n)
where not exists (select 1 from public.projects p where lower(p.name) = lower(v.n));

do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema = 'public' and table_name = 'projects' and column_name = 'has_site_stock') then
    update public.projects set has_site_stock = false where name in ('378 Elgin', '6 Manchester');
  end if;
end $$;

-- PO number codes for the new sites: the next free two-digit code.
update public.projects p
set project_code = lpad((
  select coalesce(max(case when q.project_code ~ '^[0-9]+$' then q.project_code::integer end), 0) + 1
  from public.projects q where q.project_code is not null)::text, 2, '0')
where p.name in ('378 Elgin', '6 Manchester') and p.project_code is null;

-- Repower sites, matched to the existing ones by name (e.g. "SunE Alfred LP"); one NOTICE per pattern.
do $$
declare
  r record; matched integer; om_id bigint;
begin
  for r in
    select * from (values
      ('Repower - Phase 1', '%alfred%'), ('Repower - Phase 1', '%hwy%2%'), ('Repower - Phase 1', '%highway%2%'),
      ('Repower - Phase 1', '%norfolk%'), ('Repower - Phase 1', '%odessa%'), ('Repower - Phase 1', '%rutley%'),
      ('Repower - Phase 1', '%sandhurst%'), ('Repower - Phase 1', '%unity%'),
      ('Repower - Phase 1', '378 elgin'), ('Repower - Phase 1', '6 manchester'),
      ('Repower - Phase 2', '%alfred%'), ('Repower - Phase 2', '%hwy%2%'), ('Repower - Phase 2', '%highway%2%'),
      ('Repower - Phase 2', '%odessa%'), ('Repower - Phase 2', '%sandhurst%'), ('Repower - Phase 2', '%unity%')
    ) as v(program_name, pattern)
  loop
    insert into public.program_sites (program_id, project_id)
    select g.id, p.id
    from public.programs g, public.projects p
    where g.name = r.program_name and lower(p.name) like r.pattern
      and not exists (select 1 from public.program_sites x where x.program_id = g.id and x.project_id = p.id);
    get diagnostics matched = row_count;
    if matched = 0 and not exists (
         select 1 from public.projects p, public.programs g, public.program_sites x
         where g.name = r.program_name and x.program_id = g.id and x.project_id = p.id and lower(p.name) like r.pattern) then
      raise notice '% : no site matches "%" -- add it in Admin > Projects', r.program_name, r.pattern;
    end if;
  end loop;
end $$;

-- 3. Budget categories -----------------------------------------------------------------------------

alter table public.budget_categories add column if not exists program_id bigint references public.programs(id);

update public.budget_categories c
set program_id = (select id from public.programs where name = 'Regular O&M')
where c.program_id is null and c.name !~* 'repower';

do $$
declare r record; p1 bigint;
begin
  select id into p1 from public.programs where name = 'Repower - Phase 1';
  for r in select id, name from public.budget_categories where program_id is null loop
    if exists (select 1 from public.purchase_requests where budget_category_id = r.id) then
      update public.budget_categories set program_id = p1 where id = r.id;
      raise notice 'Category "%" has POs, so it was moved to Repower - Phase 1 instead of being deleted.', r.name;
    else
      delete from public.budget_subcategories where category_id = r.id;
      delete from public.budget_categories where id = r.id;
      raise notice 'Category "%" (repower) was removed from Regular O&M.', r.name;
    end if;
  end loop;
end $$;

alter table public.budget_categories alter column program_id set not null;

-- Names are only unique within a project now ("Contingency" is on both repower lists).
alter table public.budget_categories drop constraint if exists budget_categories_name_key;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'budget_categories_program_name_key') then
    alter table public.budget_categories add constraint budget_categories_program_name_key unique (program_id, name);
  end if;
end $$;

