-- A new top layer, shown in the app as "Project": Regular O&M, Repower - Phase 1, Repower - Phase 2.
-- (In the database the table is `programs`, because `projects` is the table of sites -- what the app
-- used to call Entities and now calls Sites.)
--
--   * Each Project has its own list of Sites (`program_sites`; a site can be in several Projects) and its
--     own list of Budget Categories (`budget_categories.program_id`).
--   * Each Project has the email address vendors send invoices to (`programs.invoice_email`); a PO takes it
--     from its Project, so the PO form no longer asks.
--   * Every PO records its Project (`purchase_requests.program_id`).
--   * Spare-parts inventory is only kept for Sites in a Project that has `tracks_inventory` (Regular O&M);
--     the repower-only sites (378 Elgin, 6 Manchester) have no stock.
--
-- What it does to the data that is already there:
--   * Every site you have now goes into Regular O&M. FLOPS is renamed "Firelight Operations LP".
--   * SunE Alfred / Hwy 2 / Norfolk / Odessa / Rutley / Sandhurst / Unity are matched by name to the
--     existing sites and added to Repower 1 (and Alfred / Hwy 2 / Odessa / Sandhurst / Unity to Repower 2).
--     378 Elgin and 6 Manchester are created as new sites on Repower 1. Check the NOTICE lines it prints.
--   * Every budget category you have now becomes a Regular O&M category, except one with "repower" in its
--     name: that one is deleted if no PO uses it, otherwise moved to Repower - Phase 1 (with its POs).
--   * The two Repower projects get their own category lists (Engineering & Permitting ... Contingency).
--   * Every existing PO is put on Regular O&M (or on the project of its category).
--   * A PO's site and budget category must belong to its Project (enforced here, when they are set).
--   * The PO a Stock Transfer writes gets the Regular O&M project and its "Inventory" category.

-- 1. Projects and their sites -------------------------------------------------------------------

create table if not exists public.programs (
  id bigint generated by default as identity primary key,
  name text not null unique,
  invoice_email text,
  tracks_inventory boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.program_sites (
  program_id bigint not null references public.programs(id) on delete cascade,
  project_id bigint not null references public.projects(id) on delete cascade,
  primary key (program_id, project_id)
);

